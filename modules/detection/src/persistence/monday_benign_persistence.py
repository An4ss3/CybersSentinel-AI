@dataclass(frozen=True, slots=True)
class VerifiedMondayBenignReport:
    """Result of verifying the published MB3 report before any write."""

    report: MondayBenignNormalizationRunReport
    report_content_sha256: str
    report_file_sha256: str
    protocol_sha256: str
    event_stream_sha256: str
    rejection_audit_stream_sha256: str


def verify_frozen_mb3_report(
    repository_root: str | Path,
    report_relative_path: str = MB3_REPORT_RELATIVE_PATH,
) -> VerifiedMondayBenignReport:
    """Verify the published MB3 report is intact and self-consistent."""
    root = Path(repository_root).resolve(strict=True)
    path = root / report_relative_path
    if not path.is_file():
        raise MondayBenignMaterializationError(f"MB3 report not found: {path}")
    raw = path.read_bytes()
    report = MondayBenignNormalizationRunReport.model_validate_json(
        raw.decode("utf-8")
    )
    if report.verification_status != "verified":
        raise MondayBenignMaterializationError("MB3 report is not verified")
    if report.track != "monday_benign":
        raise MondayBenignMaterializationError("MB3 report is not the MB track")
    if len(report.partition_reports) != 1:
        raise MondayBenignMaterializationError("MB3 report must hold one partition")
    partition = report.partition_reports[0]
    if partition.output_partition != MONDAY_OUTPUT_PARTITION:
        raise MondayBenignMaterializationError(
            f"MB3 report partition must be {MONDAY_OUTPUT_PARTITION}"
        )
    if report.event_id_namespace != MB3_EVENT_ID_NAMESPACE:
        raise MondayBenignMaterializationError("MB3 report namespace mismatch")
    return VerifiedMondayBenignReport(
        report=report,
        report_content_sha256=report.content_sha256(),
        report_file_sha256=sha256(raw).hexdigest(),
        protocol_sha256=report.protocol_sha256,
        event_stream_sha256=report.canonical_event_stream_sha256,
        rejection_audit_stream_sha256=report.rejection_audit_stream_sha256,
    )


