def write_immutable_mb4_report(
    report: MondayBenignMaterializationReport,
    path: str | Path,
) -> str:
    """Publish the MB4 report immutably; return the written-byte hash.

    Mirrors the frozen publication policy: refuses to overwrite, exclusive
    create into a staging name, ``flush`` + ``os.fsync``, then atomic rename.
    """
    destination = Path(path)
    if destination.exists():
        raise FileExistsError(f"MB4 report already exists: {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = report.model_dump_json(indent=2).encode("utf-8") + b"\n"
    temporary = destination.with_name(f".{destination.name}.tmp")
    if temporary.exists():
        raise FileExistsError(f"MB4 report staging path exists: {temporary}")
    try:
        with temporary.open("xb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
    except BaseException:
        if temporary.exists():
            temporary.unlink()
        raise
    return sha256(payload).hexdigest()
