"""MB4 canonical persistence for the Monday Benign track.

Isolation
---------
This module writes **only** into ``mb4_canonical``. It never issues DDL or DML
against ``m4_canonical``, ``m6_canonical``, or the legacy ``public`` schema, and
every foreign key it relies on stays inside ``mb4_canonical``. M chain
identities appear only as recorded values for audit.

Safety ordering, learned from the M4 data-loss incident
-------------------------------------------------------
1. ``assert_expected_database`` runs before *any* statement that can write. It
   compares ``current_database()`` against a name the caller must pass
   explicitly; there is no default that could silently target production.
2. ``verify_mb4_schema`` proves the four target tables exist with the columns
   and constraints the MB4 contract requires, before a single row is inserted.
3. ``verify_frozen_mb3_report`` proves the published MB3 report is intact and
   self-consistent, before the run row is created.
4. The partial unique index ``ux_mb4_runs_verified_report`` makes a second
   *verified* materialization of the same MB3 report fail loudly at the storage
   layer. The adapter also checks for it explicitly and raises a typed error.

Determinism
-----------
Events are **not** copied from any other table. The adapter re-invokes
``StrictZeekJsonLineParserV2`` and ``StrictZeekConnFlowEndNormalizerV2`` over the
MB2 Monday ``conn.log`` under the frozen MB3 protocol, so every ``event_id`` is
regenerated by the same UUID5 derivation MB3 used. Equality is then *proven*, not
assumed: the independently recomputed canonical event-stream digest must equal
the frozen MB3 value, otherwise the run is marked ``failed`` and nothing is
declared verified.
"""
