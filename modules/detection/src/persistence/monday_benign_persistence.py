def monday_benign_pg_settings(database: str) -> dict[str, Any]:
    """Return connection parameters for one explicitly named database."""
    return {
        "host": os.getenv("POSTGRES_HOST", "localhost"),
        "port": int(os.getenv("POSTGRES_PORT", "5432")),
        "dbname": database,
        "user": os.getenv("POSTGRES_USER", "cybersentinel"),
        "password": os.getenv("POSTGRES_PASSWORD", "cybersentinel"),
    }


def get_monday_benign_connection(database: str, connect_timeout: int = 5):
    """Connect to one explicitly named database. There is no default name."""
    if not database:
        raise MondayBenignDatabaseGuardError(
            "MB4 requires an explicit target database name"
        )
    import psycopg

    return psycopg.connect(
        connect_timeout=connect_timeout, **monday_benign_pg_settings(database)
    )


def assert_expected_database(conn, expected_database: str) -> str:
    """Refuse to continue unless ``current_database()`` equals the expectation.

    This is the guard whose absence caused the M4 production data loss. It runs
    before any statement capable of writing.
    """
    with conn.cursor() as cur:
        cur.execute("SELECT current_database()")
        row = cur.fetchone()
    actual = row[0] if row else None
    if actual != expected_database:
        raise MondayBenignDatabaseGuardError(
            f"MB4 refuses to write: connected to {actual!r}, "
            f"expected {expected_database!r}"
        )
    return actual


def _strip_sql_comments(ddl: str) -> str:
    """Return the DDL with ``--`` line comments removed.

    The isolation guard below must test executable statements, not prose. The
    MB4 DDL header deliberately names ``m4_canonical`` and ``m6_canonical`` to
    document that it never touches them, so a naive substring check on the raw
    text produces a false positive.
    """
    lines = []
    for line in ddl.splitlines():
        marker = line.find("--")
        lines.append(line if marker == -1 else line[:marker])
    return "\n".join(lines)


def ensure_mb4_schema(conn) -> None:
    """Apply schema_mb.sql. Every statement is CREATE ... IF NOT EXISTS."""
    ddl_path = Path(__file__).resolve().parent / MB4_DDL_FILE_NAME
    ddl = ddl_path.read_text(encoding="utf-8")
    executable = _strip_sql_comments(ddl)
    for forbidden in ("m4_canonical", "m6_canonical"):
        if forbidden in executable:
            raise MondayBenignMaterializationError(
                f"MB4 DDL must never reference {forbidden} in a statement"
            )
    with conn.cursor() as cur:
        cur.execute(ddl)
    conn.commit()


def verify_mb4_schema(conn) -> None:
    """Prove the target schema matches the MB4 contract before any insert."""
    with conn.cursor() as cur:
        cur.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = %s ORDER BY table_name",
            (MB4_SCHEMA,),
        )
        tables = tuple(row[0] for row in cur.fetchall())
        if tables != _REQUIRED_TABLES:
            raise MondayBenignMaterializationError(
                f"MB4 schema tables mismatch: expected {_REQUIRED_TABLES}, "
                f"found {tables}"
            )

        cur.execute(
            "SELECT column_name, numeric_precision, numeric_scale "
            "FROM information_schema.columns "
            "WHERE table_schema = %s AND table_name = 'flow_end_events' "
            "AND column_name = ANY(%s) ORDER BY column_name",
            (MB4_SCHEMA, list(_EXACT_NUMERIC_COLUMNS)),
        )
        numeric = tuple(cur.fetchall())
        if len(numeric) != len(_EXACT_NUMERIC_COLUMNS):
            raise MondayBenignMaterializationError(
                "MB4 temporal columns are incomplete"
            )
        for name, precision, scale in numeric:
            if (precision, scale) != (38, 22):
                raise MondayBenignMaterializationError(
                    f"MB4 column {name} must be NUMERIC(38,22), "
                    f"found NUMERIC({precision},{scale})"
                )

        cur.execute(
            "SELECT conname FROM pg_constraint "
            "WHERE conrelid = %s::regclass ORDER BY conname",
            (f"{MB4_SCHEMA}.flow_end_events",),
        )
        constraints = {row[0] for row in cur.fetchall()}
        missing = tuple(
            name for name in _REQUIRED_EVENT_CONSTRAINTS if name not in constraints
        )
        if missing:
            raise MondayBenignMaterializationError(
                f"MB4 event table is missing constraints: {missing}"
            )

        # No foreign key may leave mb4_canonical.
        cur.execute(
            """
            SELECT c.conname, n.nspname
            FROM pg_constraint c
            JOIN pg_class t ON t.oid = c.confrelid
            JOIN pg_namespace n ON n.oid = t.relnamespace
            WHERE c.contype = 'f'
              AND c.conrelid IN (
                  SELECT oid FROM pg_class
                  WHERE relnamespace = %s::regnamespace
              )
            """,
            (MB4_SCHEMA,),
        )
        foreign = tuple(cur.fetchall())
        offending = tuple(
            (name, schema) for name, schema in foreign if schema != MB4_SCHEMA
        )
        if offending:
            raise MondayBenignMaterializationError(
                f"MB4 foreign keys must stay inside {MB4_SCHEMA}: {offending}"
            )


