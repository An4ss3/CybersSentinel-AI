class MondayBenignMaterializationReport(StrictModel):
    """Immutable evidence that MB4 reproduced the frozen MB3 event stream."""

    report_version: VersionString
    verification_status: Literal["verified"]
    track: Literal["monday_benign"]
    run_id: UUID
    target_database: StrictIdentifier
    target_schema: Literal["mb4_canonical"]
    output_partition: StrictIdentifier

    mb3_report_content_sha256: Sha256Digest
    mb3_report_file_sha256: Sha256Digest
    mb3_protocol_sha256: Sha256Digest
    mb3_event_stream_sha256: Sha256Digest
    mb3_rejection_audit_stream_sha256: Sha256Digest
    mb1_manifest_sha256: Sha256Digest
    mb2_specification_sha256: Sha256Digest
    mb2_replay_report_content_sha256: Sha256Digest
    mb3_event_id_namespace: UUID

    materialized_event_stream_sha256: Sha256Digest
    materialized_rejection_stream_sha256: Sha256Digest

    record_available_time: ExactDecimalSeconds22
    ingested_at: ExactDecimalSeconds22

    total_processed_record_count: NonNegativeInt
    total_accepted_record_count: NonNegativeInt
    total_rejected_record_count: NonNegativeInt
    persisted_event_count: NonNegativeInt
    persisted_rejection_span_count: NonNegativeInt
    persisted_rejection_count_rows: NonNegativeInt
    rejection_counts: Annotated[
        tuple[tuple[str, int], ...],
        Field(default_factory=tuple),
    ]

    started_at: UtcDateTime
    completed_at: UtcDateTime

    @model_validator(mode="after")
    def validate_report(self) -> "MondayBenignMaterializationReport":
        """Require MB coordinates, digest equality, and coherent totals."""
        if self.output_partition != MONDAY_OUTPUT_PARTITION:
            raise ValueError(f"MB4 partition must be {MONDAY_OUTPUT_PARTITION}")
        if self.mb3_event_id_namespace != MB3_EVENT_ID_NAMESPACE:
            raise ValueError(f"MB4 namespace must be {MB3_EVENT_ID_NAMESPACE}")
        if self.materialized_event_stream_sha256 != self.mb3_event_stream_sha256:
            raise ValueError(
                "MB4 cannot be verified: recomputed event stream digest differs "
                "from the frozen MB3 value"
            )
        if self.materialized_rejection_stream_sha256 != (
            self.mb3_rejection_audit_stream_sha256
        ):
            raise ValueError(
                "MB4 cannot be verified: recomputed rejection digest differs "
                "from the frozen MB3 value"
            )
        if self.total_processed_record_count != (
            self.total_accepted_record_count + self.total_rejected_record_count
        ):
            raise ValueError("MB4 totals do not cover the source")
        if self.persisted_event_count != self.total_accepted_record_count:
            raise ValueError(
                "MB4 persisted event count differs from the accepted count"
            )
        if sum(count for _, count in self.rejection_counts) != (
            self.total_rejected_record_count
        ):
            raise ValueError("MB4 rejection counts do not cover rejections")
        if self.completed_at < self.started_at:
            raise ValueError("completed_at cannot precede started_at")
        return self

    def content_sha256(self) -> str:
        """Return a formatting-independent identity for the MB4 run."""
        payload = json.dumps(
            self.model_dump(mode="json"),
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
        ).encode("utf-8")
        return sha256(payload).hexdigest()


